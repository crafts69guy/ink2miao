import type { Command, Option } from '@commander-js/extra-typings';

type AnyCommand = Command<unknown[], Record<string, unknown>, Record<string, unknown>>;

const quote = (s: string) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

/** Commands whose positional argument is a note (completed from the local state). */
const NOTE_ARGUMENT = new Set(['show', 'diff']);

function optionLine(prefix: string, o: Option): string | null {
  if (o.hidden || !o.long) return null;
  const parts = [prefix, `-l ${o.long.replace(/^--/, '')}`];
  if (o.short) parts.push(`-s ${o.short.replace(/^-/, '')}`);
  if (o.argChoices) parts.push(`-xa ${quote(o.argChoices.join(' '))}`);
  else if (/<(dir|file)>|\[dir\]/.test(o.flags)) parts.push('-rF');
  else if (o.required || o.optional) parts.push('-r');
  parts.push(`-d ${quote(o.description)}`);
  return parts.join(' ');
}

/** Fish completion generated from the command tree, so it never drifts from the CLI. */
export function fishCompletion(program: AnyCommand, hidden: ReadonlySet<string>): string {
  const bin = program.name();
  const visible = program.commands.filter((c) => !hidden.has(c.name()));
  const names = visible.flatMap((c) => [c.name(), ...c.aliases()]);
  const lines = [
    `# ${bin} fish completion — generated by \`${bin} completion fish\``,
    `complete -c ${bin} -f`,
  ];
  for (const o of program.options) {
    const line = optionLine(`complete -c ${bin}`, o as Option);
    if (line) lines.push(line);
  }
  const noSub = `complete -c ${bin} -n ${quote(`not __fish_seen_subcommand_from ${names.join(' ')}`)}`;
  for (const c of visible) {
    for (const n of [c.name(), ...c.aliases()])
      lines.push(`${noSub} -a ${n} -d ${quote(c.description())}`);
    const seen = `complete -c ${bin} -n ${quote(`__fish_seen_subcommand_from ${[c.name(), ...c.aliases()].join(' ')}`)}`;
    for (const o of c.options) {
      const line = optionLine(seen, o as Option);
      if (line) lines.push(line);
    }
    if (NOTE_ARGUMENT.has(c.name()))
      lines.push(`${seen} -xa ${quote(`(${bin} titles 2>/dev/null)`)}`);
    if (c.name() === 'completion') lines.push(`${seen} -xa fish`);
  }
  return `${lines.join('\n')}\n`;
}
